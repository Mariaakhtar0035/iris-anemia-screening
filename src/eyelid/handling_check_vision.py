"""Stage 30 follow-up: the jump test (A1) on the fine-tuned vision models' saved Ghana eyelid scores.

Added after Stage 30 showed the Ghana color-number scores jump at the cutoff, so it is reported, not pass/fail. The
held-out scores come from Stage 9 / 26 (results/stage9_vit_*cp_anemic*.json: 5 folds, 1 seed, brightness and contrast
jitter in training), on the same 388 CP-AnemiC photos (Hb < 11.0 g/dL). Same settings as configs/handling_check.yaml.

Run from the repo root: python -m src.eyelid.handling_check_vision
"""
import json

import numpy as np

from src.common.evaluate import summarize
from src.common.io import RESULTS, ROOT, load_config, save_results
from src.eyelid.dataset import load_cp_anemic
from src.eyelid.handling_check import jump_test
from src.eyelid.report import fmt
from src.eyelid.train_color import _short_commit


def main():
    base, cfg = load_config("default"), load_config("handling_check")
    seed, boot = base["seed"], base["bootstrap"]
    cp = load_cp_anemic(load_config("ceiling")["cp_anemic_subset"])
    z = cp.hb.to_numpy(float) - base["anemia_cutoff_g_dl"]["child_6_59_months"]
    y = (z < 0).astype(int)
    rng = np.random.default_rng(seed)
    out = {}
    for path in sorted(RESULTS.glob("stage9_vit_*cp_anemic*.json")):
        r = json.loads(path.read_text())["results"]
        assert r["ids"] == list(cp.id), f"{path.name}: photos differ"
        s = np.asarray(r["held_out"], float)
        name = f"{r.get('model', 'vit_b16')} fine-tuned"
        out[name] = {"source": path.name, "scores": summarize(y, s, boot["n_resamples"], boot["ci"], seed),
                     "jump": jump_test(z, s, cfg, rng, boot["n_resamples"], boot["ci"], seed)}
        print(f"{name}: {out[name]['jump']['answer']}", flush=True)
    path = save_results("stage30_vision", out, {"default": base, "handling_check": cfg})
    rows = "\n".join(
        f"| {n} | {fmt(d['scores']['auroc'])} | {fmt(d['jump']['auroc_near'])} | "
        f"{d['jump']['reference']['auroc_near_median']:.3f} (97.5%: {d['jump']['reference']['auroc_near_97_5']:.3f}) | "
        f"{d['jump']['p']:.4f} | {fmt(d['jump']['rho_anemic'])} | {d['jump']['reference']['rho_anemic_median']:+.2f} | "
        f"**{d['jump']['answer']}** |" for n, d in out.items())
    report = (
        "# Stage 30 follow-up: do the fine-tuned vision models jump at the cutoff too?\n\n"
        f"Generated by `python -m src.eyelid.handling_check_vision` at commit `{_short_commit(path)}`. Added after Stage 30 "
        "(`reports/stage30_handling_check.md`), so reported, not pass/fail. Same 388 Ghana children (CP-AnemiC, "
        "**Hb < 11.0 g/dL**), the vision models' saved held-out scores (5 folds, 1 seed, brightness and contrast jitter "
        "in training), the same jump test: near = within 1 g/dL of the cutoff, steady reference with the model's own "
        "AUROC.\n\n"
        "| model | AUROC | near-cutoff AUROC | steady reference (median) | p | rank corr. with Hb, anemic only | "
        "reference | answer |\n|---|---|---|---|---|---|---|---|\n" + rows + "\n")
    (ROOT / "reports" / "stage30_vision.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
