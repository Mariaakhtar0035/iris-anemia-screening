"""Stage 26b: does a big image model add anything to TabPFN on the 29 color numbers? (the mentors' DINOv2 question)

TabPFN on the color numbers is our best eyelid model (0.92 in Ghana children); frozen DINOv2 and VisionFM features
alone are far weaker (0.67, 0.77). Here the image features go in next to the color numbers, squeezed to a few PCA
numbers inside each training fold. Settings in configs/tabpfn_image.yaml.

Run from the repo root: python -m src.eyelid.tabpfn_image
"""
import numpy as np
from sklearn.compose import ColumnTransformer
from sklearn.decomposition import PCA
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from src.common.evaluate import auroc_change, summarize
from src.common.io import ROOT, load_config, save_results
from src.common.splits import leave_one_group_out, repeated_stratified
from src.eyelid.ceiling import fit_and_score, ladder_models, population_frames, population_inputs, train_text
from src.eyelid.report import fmt, markdown_table
from src.eyelid.train_color import _short_commit

IMAGE = {"embedding": "DINOv2", "visionfm": "VisionFM"}


def with_image(make, n_color, k, seed):
    """make() on the color columns as they are plus the image columns scaled and squeezed to k PCA numbers; every step
    is fitted on the training rows only."""
    squeeze = make_pipeline(StandardScaler(), PCA(k, random_state=seed))
    return lambda: make_pipeline(ColumnTransformer([("color", "passthrough", list(range(n_color))),
                                                    ("image", squeeze, slice(n_color, None))]), make())


def main():
    base, cfg, ceiling_cfg = load_config("default"), load_config("tabpfn_image"), load_config("ceiling")
    color_cfg, probe_cfg = load_config("color"), load_config("probe")
    seed, boot = base["seed"], base["bootstrap"]
    n_boot, ci, k = boot["n_resamples"], boot["ci"], cfg["pca_components"]
    ladder = ladder_models(color_cfg, probe_cfg, ceiling_cfg, seed)
    tabpfn, dummy = ladder["tabpfn"][1], ladder["dummy"][1]
    pops = population_inputs(population_frames(ceiling_cfg), color_cfg, probe_cfg, ceiling_cfg)

    rows = []
    for name in cfg["populations"]:
        df, x = pops[name]
        y = df.anemic.to_numpy()
        nc = x["color"].shape[1]
        runs = {"color numbers": (tabpfn, x["color"])}
        for key, label in IMAGE.items():
            if key in x:
                runs[f"{label} alone ({k} PCA)"] = (with_image(tabpfn, 0, k, seed), x[key])
                runs[f"color + {label} ({k} PCA)"] = (with_image(tabpfn, nc, k, seed), np.hstack([x["color"], x[key]]))
        splits = {"5x5 CV by photo": repeated_stratified(y, ceiling_cfg["cv"]["n_splits"], ceiling_cfg["cv"]["n_repeats"],
                                                         seed)}
        if name == "cp_anemic":
            splits["leave one hospital out"] = leave_one_group_out(df.site.to_numpy())
        for split, folds in splits.items():
            head = {"population": name, "n": len(y), "anemic": f"{y.mean():.1%}", "split": split}
            rows += [head | {"model": "dummy (prior)", "input": "-", "train": "-",
                             **summarize(y, fit_and_score(dummy, x["color"], y, folds)[0], n_boot, ci, seed)},
                     head | {"model": "rule_low_redness", "input": "color", "train": "-",
                             **summarize(y, x["rule"], n_boot, ci, seed)}]
            held = {}
            for inp, (make, X) in runs.items():
                held[inp], train = fit_and_score(make, X, y, folds)
                row = head | {"model": "tabpfn", "input": inp, "train": train_text(train),
                              **summarize(y, held[inp], n_boot, ci, seed)}
                if inp != "color numbers":
                    row["vs_color"] = auroc_change(y, held[inp], held["color numbers"], n_boot, ci, seed)
                rows.append(row)
                print(f"done: {name} {split} {inp}: {row['auroc']['estimate']:.3f}", flush=True)

    path = save_results("stage26_tabpfn_image", {"rows": rows},
                        {"default": base, "tabpfn_image": cfg, "ceiling": ceiling_cfg, "color": color_cfg,
                         "probe": probe_cfg})
    helps = [f"{r['population']}, {r['split']}, {r['input']}" for r in rows
             if r["input"].startswith("color +") and r["vs_color"]["lo"] > 0]
    gains = [f"| {r['population']} | {r['split']} | {r['input']} | {fmt(r['auroc'])} | {fmt(r['vs_color'])} |"
             for r in rows if "vs_color" in r]
    report = (
        "# Stage 26b: TabPFN on the color numbers plus DINOv2 or VisionFM features\n\n"
        f"Generated by `python -m src.eyelid.tabpfn_image` at commit `{_short_commit(path)}`; settings in "
        "`configs/tabpfn_image.yaml`. The mentors asked about DINOv2; TabPFN on 29 color numbers is our best eyelid "
        "model, so this tests whether image-model features add to it.\n\n"
        "- **Anemia:** Ghana children (CP-AnemiC, the 388 photos with no copy): Hb < 11.0 g/dL. India and Italy "
        "(Eyes-Defy adults): WHO by sex, women < 12.0, men < 13.0 g/dL. One cutoff per dataset; nothing is carried "
        "between datasets.\n"
        f"- **Image features:** frozen DINOv2-small (CLS + mean patch, 768 numbers) and VisionFM (eye-pretrained), "
        f"from the caches; scaled and squeezed to {k} PCA numbers inside each training fold.\n"
        f"- **Split:** 5-fold CV x 5 repeats by photo (one photo per person); Ghana also leaves one hospital out. "
        f"Bootstrap 95% CIs, {n_boot} resamples; changes are paired (same photos). **train** = AUROC on the fold's own "
        "training photos.\n"
        "- **Answer, fixed before running:** image features help if color + image beats color alone (paired CI above "
        "0).\n\n"
        f"## Answer\n\nColor + image beats color alone for: {', '.join(helps) or 'none'}.\n\n"
        "## Change against color numbers alone (TabPFN)\n\n"
        "| population | split | input | AUROC | change vs color alone |\n|---|---|---|---|---|\n" + "\n".join(gains)
        + "\n\n## All results\n\n"
        + markdown_table(rows, ["population", "n", "anemic", "split", "model", "input", "train"],
                         {"auroc": "AUROC", "pr_auc": "PR-AUC", "sens_at_90_spec": "Sens @ 90% spec"}) + "\n"
    )
    (ROOT / "reports" / "stage26_tabpfn_image.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
