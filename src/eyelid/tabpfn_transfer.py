"""TabPFN across datasets: the best Ghana eyelid model (0.92 within CP-AnemiC, Stage 9) on adults in Italy and India,
and the reverse. Same setup as Stage 5 (src/eyelid/cross_dataset.py): fit on all of one dataset, score all of the other
unchanged, on the 29 color numbers of the hand-segmented palpebral conjunctiva. The other color models and the
untrained rule run next to it. Italy's early batch (folders 1-31) is scored on its own, since the batch alone gives
Italian anemia away (Stage 10).

Run from the repo root: python -m src.eyelid.tabpfn_transfer
"""
import numpy as np

from src.common.evaluate import summarize
from src.common.io import ROOT, load_config, save_results
from src.eyelid.ceiling import ladder_models
from src.eyelid.cross_dataset import inputs, load_eyes_defy
from src.eyelid.dataset import load_cp_anemic
from src.eyelid.report import markdown_table
from src.eyelid.train_color import _short_commit
from src.nails import COLUMNS, METRICS


def main():
    base, cfg, color_cfg, ceiling_cfg, debias_cfg = (load_config(n) for n in
                                                     ("default", "cross_dataset", "color", "ceiling", "debias"))
    seed, boot = base["seed"], base["bootstrap"]
    models = {n: make for n, (kind, make) in ladder_models(color_cfg, load_config("probe"), ceiling_cfg, seed).items()
              if kind == "color"}

    cp, ed = load_cp_anemic(cfg["cp_anemic_subset"]), load_eyes_defy(cfg)
    data = {"cp_anemic": (cp, inputs(cp, None, color_cfg)), "eyes_defy": (ed, inputs(ed, None, color_cfg))}
    italy = (ed.country == "Italy").to_numpy()
    early = italy & (ed.id.str.split("_").str[1].astype(int) <= debias_cfg["italy_early_batch_last_folder"]).to_numpy()
    subsets = {"eyes_defy": {"all": np.ones(len(ed), bool), "India": (ed.country == "India").to_numpy(),
                             "Italy": italy, "Italy early batch": early},
               "cp_anemic": {"all": np.ones(len(cp), bool)}}

    rows = []
    for src, dst in (("cp_anemic", "eyes_defy"), ("eyes_defy", "cp_anemic")):
        (sdf, sx), (ddf, dx) = data[src], data[dst]
        ys, yd = sdf.anemic.to_numpy(), ddf.anemic.to_numpy()
        scores = {name: make().fit(sx["color"], ys).predict_proba(dx["color"])[:, 1] for name, make in models.items()}
        scores["rule_low_redness (no training)"] = dx["rule"]
        for subset, m in subsets[dst].items():
            for name, s in scores.items():
                rows.append({"train -> test": f"{src} -> {dst}", "test set": subset, "n": int(m.sum()),
                             "anemic": f"{yd[m].mean():.1%}", "model": name,
                             **summarize(yd[m], s[m], boot["n_resamples"], boot["ci"], seed, metrics=METRICS)})
            print(f"done: {src} -> {dst} {subset}", flush=True)

    path = save_results("tabpfn_transfer", {"n_cp_anemic": len(cp), "n_eyes_defy": len(ed), "rows": rows},
                        {"default": base, "cross_dataset": cfg, "color": color_cfg, "ceiling": ceiling_cfg,
                         "debias": debias_cfg})
    report = (
        "# TabPFN across datasets\n\n"
        f"Generated by `python -m src.eyelid.tabpfn_transfer` at commit `{_short_commit(path)}`. Does the best Ghana "
        "eyelid model (TabPFN, 0.919 within CP-AnemiC, `stage9_ceiling.md`) still work on another dataset, unchanged? "
        "Same setup as Stage 5 (`stage5_cross_dataset.md`).\n\n"
        f"- **Labels:** CP-AnemiC, the {len(cp)} photos with no copy, anemic = Hb < 11.0 g/dL (children). Eyes-Defy, "
        f"{len(ed)} photos with Hb, anemic = WHO adult cutoffs by sex (women < 12.0, men < 13.0 g/dL; pregnancy not "
        "recorded). The cutoffs differ between the datasets by design.\n"
        "- **Input:** the 29 color numbers of the hand-segmented palpebral conjunctiva on both sides. Each model is fit "
        "on all of one dataset and applied unchanged to the other. `rule_low_redness`: minus mean a*, no training.\n"
        f"- **Italy early batch:** folders 1-{debias_cfg['italy_early_batch_last_folder']} ({int(early.sum())} photos, "
        f"{int(ed.anemic[early].sum())} anemic). Almost all Italian anemia is in this batch (Stage 10), so it is the "
        "Italy test that recognizing the batch can't pass.\n"
        f"- Bootstrap 95% CIs, {boot['n_resamples']} resamples, one photo per person. Share tested to catch 90%: "
        "testing in random order needs 90%; lower is better.\n\n"
        + markdown_table(rows, ["train -> test", "test set", "n", "anemic", "model"], COLUMNS) + "\n"
    )
    (ROOT / "reports" / "tabpfn_transfer.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
