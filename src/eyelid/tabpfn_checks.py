"""Shortcut checks for TabPFN (follow-up to M14, docs/eyelid_followup.md Step 12): are its 0.92 on Ghana eyelids and
0.91 / 0.80 on Ghana palm and nails pallor color, or something a model can read without color?

1. The no-color control with TabPFN itself: the image size and cut-out shape numbers the random-forest control uses.
   A strong learner could find a leak in them that a random forest misses.
2. CP-AnemiC leave one hospital out: train on 9 hospitals, score the 10th, for TabPFN and gradient boosting. Plus a
   model that sees only the hospital (within-hospital CV), to show what a hospital shortcut alone could give.

Run from the repo root: python -m src.eyelid.tabpfn_checks
"""
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import OneHotEncoder

from src.common.evaluate import summarize
from src.common.io import ROOT, load_config, save_results
from src.common.splits import leave_one_group_out, repeated_stratified
from src.eyelid.ceiling import fit_and_score, ladder_models, train_text
from src.eyelid.color_features import feature_table, image_properties
from src.eyelid.dataset import load_cp_anemic
from src.eyelid.report import markdown_table
from src.eyelid.train_color import _short_commit
from src.ghana_sites import load_site


def main():
    base, cfg, color_cfg, sites_cfg = (load_config(n) for n in ("default", "ceiling", "color", "ghana_sites"))
    seed, boot = base["seed"], base["bootstrap"]
    models = {n: make for n, (kind, make) in ladder_models(color_cfg, load_config("probe"), cfg, seed).items()
              if kind == "color"}
    hospital_only = lambda: make_pipeline(OneHotEncoder(handle_unknown="ignore"),
                                          LogisticRegression(max_iter=5000, random_state=seed))

    cp = load_cp_anemic(cfg["cp_anemic_subset"])  # the 388 photos of Stage 9
    sets = {"eyelid (CP-AnemiC)": (cp, [ROOT / p for p in cp.image_path], cfg["cv"])}
    for site, folder in sites_cfg["sites"].items():
        photos, _ = load_site(folder, base["cp_anemic_near_duplicate"])
        sets[site] = (photos, list(photos.path), sites_cfg["cv"])

    rows = []
    for name, (df, paths, cv) in sets.items():
        y = df.anemic.to_numpy()
        X = {"color numbers": feature_table(paths, df.index, alpha_threshold=color_cfg["roi"]["alpha_threshold"]).to_numpy(),
             "no color (size and shape)": image_properties(paths, df.index).to_numpy()}
        splits = {"5x5 CV by photo": repeated_stratified(y, cv["n_splits"], cv["n_repeats"], seed)}
        if name.startswith("eyelid"):
            splits["leave one hospital out"] = leave_one_group_out(df.site.to_numpy())
        for split, folds in splits.items():
            runs = [("tabpfn", "color numbers"), ("tabpfn", "no color (size and shape)")]
            if split == "leave one hospital out":
                runs = [("tabpfn", "color numbers"), ("hist_gradient_boosting", "color numbers")]
            for model, inp in runs:
                held_out, train_auroc = fit_and_score(models[model], X[inp], y, folds)
                rows.append({"data": name, "n": len(y), "split": split, "model": model, "input": inp,
                             "train": train_text(train_auroc),
                             **summarize(y, held_out, boot["n_resamples"], boot["ci"], seed)})
                print(f"done: {name} {split} {model} {inp}", flush=True)
        if name.startswith("eyelid"):  # a held-out hospital has no history, so this only runs within hospitals
            held_out, train_auroc = fit_and_score(hospital_only, df[["site"]].to_numpy(), y, splits["5x5 CV by photo"])
            rows.append({"data": name, "n": len(y), "split": "5x5 CV by photo", "model": "logistic_regression",
                         "input": "hospital only", "train": train_text(train_auroc),
                         **summarize(y, held_out, boot["n_resamples"], boot["ci"], seed)})

    path = save_results("tabpfn_checks", {"rows": rows},
                        {"default": base, "ceiling": cfg, "color": color_cfg, "ghana_sites": sites_cfg})
    report = (
        "# TabPFN shortcut checks\n\n"
        f"Generated by `python -m src.eyelid.tabpfn_checks` at commit `{_short_commit(path)}`. Follow-up to M14 "
        "(`docs/eyelid_followup.md`, Step 12): is TabPFN's high score pallor color, or something it can read without "
        "color?\n\n"
        "- **Labels:** CP-AnemiC Hb < 11.0 g/dL, the 388 photos with no copy (as in Stage 9). Ghana palm and nails: "
        "the dataset's own label from the file name, cutoff not stated (Stage 13).\n"
        "- **no color (size and shape):** image width, height, aspect and the opaque and edge shares of the cut-out, "
        "the inputs of the random-forest no-color control. Near 0.5 = no shortcut TabPFN can find there.\n"
        "- **leave one hospital out:** CP-AnemiC only (10 hospitals); pooled held-out scores, so a hospital's photos "
        "are never in training when it is scored. Close to the 5x5 CV score = not leaning on the hospital.\n"
        "- **hospital only:** logistic regression on the hospital alone, within-hospital 5x5 CV: what knowing the "
        "hospital is worth by itself.\n"
        f"- Bootstrap 95% CIs, {boot['n_resamples']} resamples. **train** = AUROC of each fold's model on its own "
        "training photos, mean (min-max).\n\n"
        + markdown_table(rows, ["data", "n", "split", "model", "input", "train"]) + "\n"
    )
    (ROOT / "reports" / "tabpfn_checks.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
