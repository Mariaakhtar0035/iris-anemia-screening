"""Stage 4: logistic regression probe on frozen DINOv2 embeddings, on the same folds as Stage 3.

Run from the repo root: python -m src.eyelid.train_probe  (computes embeddings first if not cached)
"""
import json

import numpy as np
from sklearn.linear_model import LogisticRegressionCV
from sklearn.model_selection import StratifiedKFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from src.common.evaluate import oof_scores, summarize
from src.common.io import RESULTS, ROOT, load_config, save_results
from src.common.splits import leave_one_group_out, repeated_stratified, repeated_stratified_grouped
from src.eyelid.dataset import load_cp_anemic
from src.eyelid.embed import load_embeddings
from src.eyelid.report import markdown_table

REPORTS = ROOT / "reports"
FROM_STAGE3 = ["dummy", "rule_low_redness", "negative_control_rf_no_color", "logistic_regression", "random_forest"]


def probe_factory(cfg, seed):
    p = cfg["probe"]
    # The regularization strength is picked by an inner CV inside each outer training fold.
    return lambda: make_pipeline(
        StandardScaler(),
        LogisticRegressionCV(
            Cs=p["Cs"], cv=StratifiedKFold(p["inner_folds"], shuffle=True, random_state=seed),
            scoring="roc_auc", max_iter=p["max_iter"], random_state=seed,
        ),
    )


def main():
    base, color_cfg, cfg = load_config("default"), load_config("color"), load_config("probe")
    seed, boot = base["seed"], base["bootstrap"]
    n_splits, n_repeats = color_cfg["cv"]["n_splits"], color_cfg["cv"]["n_repeats"]
    emb = load_embeddings(cfg)
    row_of = {i: k for k, i in enumerate(emb["ids"])}
    make_probe = probe_factory(cfg, seed)

    unique, singletons, everything = (load_cp_anemic(s) for s in ("unique", "singletons", "all"))
    experiments = {  # identical subsets, order and seeds as Stage 3, so the folds are identical
        "cv_5x5_no_copies": (singletons, repeated_stratified(singletons.anemic, n_splits, n_repeats, seed)),
        "leave_one_hospital_out": (singletons, leave_one_group_out(singletons.site)),
        "cv_5x5_distinct_photos": (unique, repeated_stratified(unique.anemic, n_splits, n_repeats, seed)),
    }

    rows = []
    for exp, (data, folds) in experiments.items():
        y = data.anemic.to_numpy()
        rows_idx = [row_of[i] for i in data.id]
        for fs in cfg["feature_sets"]:
            scores = oof_scores(make_probe, emb[fs][rows_idx], y, folds)
            rows.append({"experiment": exp, "n": len(y), "model": f"dinov2_probe[{fs}]",
                         **summarize(y, scores, boot["n_resamples"], boot["ci"], seed)})
            print(f"done: {exp}, {fs}")

    leak_rows = []
    y_all, groups = everything.anemic.to_numpy(), everything.photo_group.to_numpy()
    X_all = emb["cls_and_patch_mean"][[row_of[i] for i in everything.id]]
    for split_name, folds in {
        "random rows (copies can leak)": repeated_stratified(y_all, n_splits, n_repeats, seed),
        "grouped by photo (no leak)": repeated_stratified_grouped(y_all, groups, n_splits, n_repeats, seed),
    }.items():
        scores = oof_scores(make_probe, X_all, y_all, folds)
        leak_rows.append({"split": split_name, "n": len(y_all), "model": "dinov2_probe[cls_and_patch_mean]",
                          **summarize(y_all, scores, boot["n_resamples"], boot["ci"], seed, groups=groups)})
        print(f"done: leakage check, {split_name}")

    device = str(emb["device"])
    path = save_results("stage4_probe", {"device": device, "main": rows, "leakage_check": leak_rows},
                        {"default": base, "color": color_cfg, "probe": cfg})

    # One table with the Stage 3 color baseline (gray-world off, its better setting) on the same folds.
    stage3 = json.loads((RESULTS / "stage3_color.json").read_text())["results"]
    color_rows = [r for r in stage3["main"] if not r["gray_world"] and r["model"] in FROM_STAGE3]
    combined = []
    for exp in experiments:
        combined += [r for r in color_rows if r["experiment"] == exp]
        combined += [r for r in rows if r["experiment"] == exp]
    combined_leak = [r for r in stage3["leakage_check"] if r["model"] in ("random_forest",)] + leak_rows

    git = json.loads(path.read_text())["git"]
    commit = git["commit"][:7] + (" + uncommitted changes" if git["dirty"] else "")
    table = markdown_table(combined, ["experiment", "n", "model"])
    leak_table = markdown_table(combined_leak, ["split", "n", "model"])
    (REPORTS / "stage4_probe.md").write_text(
        "# Stage 4: frozen DINOv2 probe vs color baseline (CP-AnemiC)\n\n"
        f"Generated by `python -m src.eyelid.train_probe` at commit `{commit}`, embeddings computed on `{device}`. "
        f"Model `{cfg['model_id']}` at revision `{cfg['revision'][:10]}`. Anemia = Hb < 11.0 g/dL. "
        "Bootstrap 95% CIs, 2000 resamples. Color rows come from Stage 3 (gray-world off) on identical folds.\n\n"
        "- `dinov2_probe[...]`: standardized embedding, logistic regression with C picked by inner 5-fold CV "
        "(AUROC) inside every outer training fold. Images padded to a square on the ImageNet mean color, "
        "resized to 224, no center crop.\n"
        "- Experiments and subsets as in [Stage 3](stage3_color.md); `cv_5x5_no_copies` is the headline.\n\n"
        f"{table}\n\n## Leakage check: all 710 rows\n\n{leak_table}\n"
    )
    print(f"\n{table}\n\nLeakage check:\n{leak_table}\n\ndevice: {device}; saved {path.relative_to(ROOT)} and reports/stage4_probe.md")


if __name__ == "__main__":
    main()
