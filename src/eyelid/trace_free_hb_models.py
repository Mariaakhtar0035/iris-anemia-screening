"""Stage 31 follow-up: do Stage 16's other Hb regressors (random forest, gradient boosting) jump at the cutoff too?

Added after Stage 31, whose part C covered ridge and the TabPFN regressor only; gradient boosting gives the best
Ghana Hb error in Stage 16 (1.38 g/dL). Same datasets, cutoffs, folds and jump test as Stage 31 (configs/trace_free.yaml,
handling_check.yaml), Stage 16's settings (hb_regression.yaml). Same answer rule as Stage 31 C: a model "carries the
trace" on a dataset if its estimate jumps.

Run from the repo root: python -m src.eyelid.trace_free_hb_models
"""
import numpy as np

from src.common.evaluate import summarize
from src.common.io import ROOT, load_config, save_results
from src.common.metrics import bootstrap_ci
from src.eyelid.handling_check import NAMES, datasets, folds_for, jump_test
from src.eyelid.hb_regression import mae, oof_regression, regressors
from src.eyelid.report import fmt
from src.eyelid.train_color import _short_commit

MODELS = ("random_forest", "hist_gradient_boosting")


def main():
    base, cfg, color_cfg = load_config("default"), load_config("trace_free"), load_config("color")
    jump_cfg, hb_cfg = load_config("handling_check"), load_config("hb_regression")
    seed, boot = base["seed"], base["bootstrap"]
    n_boot, ci = boot["n_resamples"], boot["ci"]
    rng = np.random.default_rng(seed)
    makers = {m: regressors(hb_cfg, seed)[m] for m in MODELS}
    out = {}
    for name, d in datasets(cfg, base, color_cfg, seed).items():
        z, y = d["hb"] - d["cut"], d["y"]
        folds = folds_for(y, d["groups"], cfg["cv"], seed)
        out[name] = {}
        for m, make in makers.items():
            est = oof_regression(make, d["X"], z, folds)
            out[name][m] = {"mae": bootstrap_ci(mae, z, est.mean(0), n_boot, ci, seed=seed),
                            "scores": summarize(y, -est, n_boot, ci, seed),
                            "jump": jump_test(z, -est.mean(0), jump_cfg, rng, n_boot, ci, seed)}
            print(f"done {name} {m}: {out[name][m]['jump']['answer']}", flush=True)
        save_results("stage31_hb_models", out, {"default": base, "trace_free": cfg, "handling_check": jump_cfg,
                                                "hb_regression": hb_cfg})
    path = save_results("stage31_hb_models", out, {"default": base, "trace_free": cfg, "handling_check": jump_cfg,
                                                   "hb_regression": hb_cfg})
    rows = "\n".join(
        f"| {NAMES[n]} | {m} | {fmt(r['mae'])} | {fmt(r['scores']['auroc'])} | {fmt(r['scores']['pr_auc'])} | "
        f"{fmt(r['scores']['sens_at_90_spec'])} | {fmt(r['jump']['auroc_near'])} | "
        f"{r['jump']['reference']['auroc_near_median']:.3f} | {r['jump']['p']:.4f} | **{r['jump']['answer']}** | "
        f"{fmt(r['jump']['rho_anemic'])} |" for n, d in out.items() for m, r in d.items())
    report = (
        "# Stage 31 follow-up: do Stage 16's random forest and gradient boosting Hb models jump at the cutoff?\n\n"
        f"Generated by `python -m src.eyelid.trace_free_hb_models` at commit `{_short_commit(path)}`. Added after Stage 31 "
        "(`reports/stage31_trace_free.md`, part C: ridge and the TabPFN regressor), because gradient boosting gives "
        "Stage 16's best Ghana Hb error. Same datasets, **cutoffs** (Ghana Hb < 11.0 g/dL; India and Italy WHO by sex, "
        "women < 12.0, men < 13.0; Moscow < 12.0 for everyone), 5-fold CV x 5 repeats and jump test as Stage 31; Stage 16's "
        "model settings. Target: Hb minus the person's cutoff; score = minus the estimate.\n\n"
        "| dataset | model | Hb error (MAE, g/dL) | AUROC | PR-AUC | sens @ 90% spec | near-cutoff AUROC | steady "
        "reference (median) | p | answer | rank corr. with Hb, anemic only |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|\n" + rows + "\n")
    (ROOT / "reports" / "stage31_hb_models.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
