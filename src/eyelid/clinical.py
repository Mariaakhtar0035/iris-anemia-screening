"""Step 4: what the eyelid models would mean in a clinic (mentor advice M13, docs/eyelid_followup.md).

For each population: to catch 80/90/95/100% of anemic people, what share of everyone must be sent for a blood test,
and what share of those tested are anemic? Also PR curves against the prevalence line (a model with no signal sits
on that line). Scores come from Stage 9's folds: the redness rule, the random forest and the DINOv2 probe are refit
here, and the fine-tuned ViT is read from results/stage9_vit_*.json.

Run from the repo root: python -m src.eyelid.clinical
"""
import json
from functools import partial

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from sklearn.metrics import precision_recall_curve

from src.common.evaluate import summarize
from src.common.io import RESULTS, ROOT, load_config, save_results
from src.common.metrics import pr_auc, precision_at_sensitivity, share_tested_at_sensitivity
from src.common.splits import repeated_stratified
from src.eyelid.ceiling import FIGURES, fit_and_score, ladder_models, population_frames, population_inputs
from src.eyelid.report import markdown_table


def main():
    base, cfg, ceiling = load_config("default"), load_config("clinical"), load_config("ceiling")
    color_cfg, probe_cfg = load_config("color"), load_config("probe")
    seed, boot = base["seed"], base["bootstrap"]
    early_last = load_config("populations")["italy_early_batch_last_folder"]
    pops = population_inputs(population_frames(ceiling), color_cfg, probe_cfg)
    models = ladder_models(color_cfg, probe_cfg, ceiling, seed)
    metrics = {f"share_{s}": partial(share_tested_at_sensitivity, sens=s) for s in cfg["sensitivities"]}
    metrics |= {f"precision_{s}": partial(precision_at_sensitivity, sens=s) for s in cfg["sensitivities"]}
    metrics["pr_auc"] = pr_auc

    rows, curves = [], {}
    for name, (df, x) in pops.items():
        y = df.anemic.to_numpy()
        folds = repeated_stratified(y, ceiling["cv"]["n_splits"], ceiling["cv"]["n_repeats"], seed)
        scores = {"rule_low_redness": x["rule"]}
        for model in cfg["models"]:
            kind, make = models[model]
            scores[model] = fit_and_score(make, x[kind], y, folds)[0].mean(0)
        vit = RESULTS / f"stage9_vit_{name}_jitter.json"
        if vit.exists():
            r = json.loads(vit.read_text())["results"]
            assert r["ids"] == df.id.tolist()
            scores["vit_b16_finetuned (1 seed)"] = np.array(r["held_out"])
        subsets = {name: np.ones(len(y), bool)}
        if name == "eyes_defy_italy":  # the Italy check the early batch alone can't pass (Stage 10)
            subsets["eyes_defy_italy, early batch"] = (df.id.str.split("_").str[1].astype(int) <= early_last).to_numpy()
        for subset, m in subsets.items():
            for model, s in scores.items():
                rows.append({"population": subset, "n": int(m.sum()), "anemic": f"{y[m].mean():.1%}", "model": model,
                             **summarize(y[m], s[m], boot["n_resamples"], boot["ci"], seed, metrics=metrics)})
                curves[(subset, model)] = (y[m], s[m])
        print(f"{name} done", flush=True)

    FIGURES.mkdir(parents=True, exist_ok=True)
    panels = list(dict.fromkeys(p for p, _ in curves))
    fig, axes = plt.subplots(1, len(panels), figsize=(3.6 * len(panels), 3.6), sharey=True)
    for ax, panel in zip(axes, panels):
        for i, ((p, model), (y, s)) in enumerate((k, v) for k, v in curves.items() if k[0] == panel):
            prec, rec, _ = precision_recall_curve(y, s)
            ax.plot(rec, prec, color=f"C{i}", lw=1.2, label=model)
        ax.axhline(y.mean(), color="grey", ls="--", lw=0.8, label="prevalence (no signal)")
        ax.set_title(panel.replace("_", " "), fontsize=9)
        ax.set_xlabel("recall (share of anemic caught)")
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_ylabel("precision (share of tested who are anemic)")
    axes[0].legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(FIGURES / "clinical_pr_curves.png", dpi=150)

    sens = cfg["sensitivities"]
    share_cols = {f"share_{s}": f"tested to catch {s:.0%}" for s in sens}
    prec_cols = {f"precision_{s}": f"anemic among tested, {s:.0%}" for s in sens}
    text = (
        "# What the eyelid models would mean in a clinic\n\n"
        "Generated by `python -m src.eyelid.clinical`; settings in `configs/clinical.yaml`. Mentor advice M13 "
        "(`docs/eyelid_followup.md`). Held-out scores from Stage 9's folds (5x5 CV by photo, averaged; the ViT has one "
        "seed). Anemic: CP-AnemiC Hb < 11.0 g/dL (children, the 388 photos with no copy); Eyes-Defy WHO by sex "
        f"(women < 12.0, men < 13.0). Bootstrap 95% CIs ({boot['n_resamples']} resamples).\n\n"
        "How to read it: a clinic picks how many anemic people it can afford to miss. **Tested to catch 90%** is the "
        "share of *everyone* who must get a blood test, highest scores first, to catch 90% of the anemic ones. Testing "
        "everyone catches 100% at a load of 1.0, so a useful score has to land well below 1.0. **Anemic among tested** "
        "is the precision there. Which row matters is a clinical choice: what a missed anemic person costs against an "
        "unneeded blood test. That has to come from clinicians, not from us.\n\n"
        "## Share of everyone sent for a blood test\n\n"
        + markdown_table(rows, ["population", "n", "anemic", "model"], share_cols)
        + "\n\n## Share of those tested who are anemic (precision)\n\n"
        + markdown_table(rows, ["population", "n", "anemic", "model"], {**prec_cols, "pr_auc": "PR-AUC"})
        + "\n\n![PR curves](figures/clinical_pr_curves.png)\n"
    )
    (ROOT / "reports" / "clinical_eyelid.md").write_text(text)
    print(text)
    save_results("clinical_eyelid", {"rows": rows}, {"default": base, "clinical": cfg, "ceiling": ceiling})


if __name__ == "__main__":
    main()
