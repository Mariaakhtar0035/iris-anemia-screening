"""Stage 28: do the nail and the skin next to it say more together than the nail alone? (Moscow, fixed light box)

Stage 12b subtracted the skin from the nail and lost signal, because the skin pales with anemia too. Here both sets of
color numbers go in side by side, so the model can weigh them. Settings in configs/nails_skin.yaml.

Run from the repo root: python -m src.nails_skin
"""
import numpy as np
import pandas as pd

from src.common.evaluate import auroc_change, summarize
from src.common.io import ROOT, load_config, save_results
from src.common.splits import leave_one_group_out, repeated_stratified
from src.eyelid.ceiling import fit_and_score, ladder_models, train_text
from src.eyelid.report import fmt, markdown_table
from src.eyelid.train_color import _short_commit
from src.nails import box_sizes, load_nails, photo_features

NAIL, SKIN, EARLY, LATE = "nail", "skin", "nail + skin (one model)", "nail + skin (scores averaged)"


def main():
    base, cfg, nails_cfg = load_config("default"), load_config("nails_skin"), load_config("nails")
    color_cfg, ceiling_cfg = load_config("color"), load_config("ceiling")
    seed, boot = base["seed"], base["bootstrap"]
    n_boot, ci = boot["n_resamples"], boot["ci"]

    df = load_nails(nails_cfg)
    y, sessions = df.anemic.to_numpy(), df.session.to_numpy()
    assert ((df.hb_g_per_l < nails_cfg["anemia_cutoff_g_per_l"]) == (y == 1)).all()
    nail, _, skin = (pd.DataFrame(list(f)) for f in zip(*[
        photo_features(*row) for row in zip(df.image_path, df.nail_boxes, df.skin_boxes)]))
    X = {NAIL: nail.to_numpy(), SKIN: skin.to_numpy(), EARLY: np.hstack([nail.to_numpy(), skin.to_numpy()])}
    sizes = np.array([box_sizes(n) + box_sizes(s) for n, s in zip(df.nail_boxes, df.skin_boxes)])
    feature = color_cfg["rule_feature"]
    rules = {NAIL: -nail[feature].to_numpy(), SKIN: -skin[feature].to_numpy()}
    rank = lambda s: pd.Series(s).rank().to_numpy()
    rules[LATE] = (rank(rules[NAIL]) + rank(rules[SKIN])) / 2
    ladder = ladder_models(color_cfg, load_config("probe"), ceiling_cfg, seed)
    models = {m: ladder[m][1] for m in cfg["models"]}

    cv = nails_cfg["cv"]
    splits = {"5x5 CV by patient": repeated_stratified(y, cv["n_splits"], cv["n_repeats"], seed),
              "leave one session out": leave_one_group_out(sessions)}
    rows = []
    for split, folds in splits.items():
        head = {"split": split, "n": len(y), "anemic": f"{y.mean():.1%}"}

        def add(model, inp, scores, train="-", ref=None):
            row = head | {"model": model, "input": inp, "train": train, **summarize(y, scores, n_boot, ci, seed)}
            if ref is not None:
                row["vs_nail"] = auroc_change(y, scores, ref, n_boot, ci, seed)
            rows.append(row)

        add("dummy (prior)", "-", fit_and_score(ladder["dummy"][1], X[NAIL], y, folds)[0])
        held_sizes, train = fit_and_score(models["random_forest"], sizes, y, folds)
        add("random_forest", "no color: nail and skin box sizes", held_sizes, train_text(train))
        for inp, s in rules.items():
            add("rule_low_redness", inp, s, ref=None if inp == NAIL else rules[NAIL])
        for name, make in models.items():
            held = {}
            for inp, x in X.items():
                held[inp], train = fit_and_score(make, x, y, folds)
                add(name, inp, held[inp], train_text(train), None if inp == NAIL else held[NAIL])
            add(name, LATE, (held[NAIL] + held[SKIN]) / 2, ref=held[NAIL])
            print(f"done: {split} {name}", flush=True)

    path = save_results("stage28_nails_skin", {"rows": rows},
                        {"default": base, "nails_skin": cfg, "nails": nails_cfg, "color": color_cfg, "ceiling": ceiling_cfg})
    wins = [f"{r['model']}, {r['input']}, {r['split']} ({fmt(r['vs_nail'])})" for r in rows
            if r["input"] in (EARLY, LATE) and r["vs_nail"]["lo"] > 0]
    report = (
        "# Stage 28: fingernail and skin color numbers together\n\n"
        f"Generated by `python -m src.nails_skin` at commit `{_short_commit(path)}`; settings in "
        "`configs/nails_skin.yaml`. Data: Yakimov et al. 2024 (Moscow adults, one photo each in a fixed light box).\n\n"
        f"- **Anemic = Hb < 12.0 g/dL (120 g/L) for everyone**, {y.sum()} of {len(y)} (no sex column, so one adult "
        "cutoff; men between 12.0 and 13.0 count as not anemic).\n"
        "- **Inputs:** the 29 color numbers of the nail boxes, of the skin boxes just behind each nail, both side by "
        "side in one model (58 numbers), and the mean of the nail model's and the skin model's scores. For the "
        "untrained rule, the mean of the two redness ranks.\n"
        "- **Baselines:** dummy, the redness rule, and a random forest on the box sizes only (no color).\n"
        "- **Splits:** 5-fold CV x 5 repeats by patient, and leave one photo session out. **train** = AUROC on the "
        f"fold's own training photos. Bootstrap 95% CIs, {n_boot} resamples; **change vs nail** is paired (same "
        "people).\n"
        "- **Answer, fixed before running:** together they help if nail + skin beats the nail alone with the CI of "
        "the change above 0.\n\n"
        f"## Answer\n\nNail + skin beats the nail alone for: {'; '.join(wins) or 'none'}.\n\n## All results\n\n"
        + markdown_table(rows, ["split", "model", "input", "train"],
                         {"auroc": "AUROC", "vs_nail": "Change vs nail", "pr_auc": "PR-AUC",
                          "sens_at_90_spec": "Sens @ 90% spec"}) + "\n"
    )
    (ROOT / "reports" / "stage28_nails_skin.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
